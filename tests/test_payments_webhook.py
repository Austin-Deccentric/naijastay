"""HMAC webhook tests via TestClient.

Signing mirrors `mock_payment_provider.sign`: HMAC-SHA256 hex over the exact
raw JSON bytes with the secret read from `.env` (`WEBHOOK_SECRET`). The router
verifies the seal on `await request.body()` *before* parsing JSON, so tests
POST raw `content=` bytes, not `json=` (which would not let us control the
exact signed bytes).
"""

from datetime import timedelta

import pytest

pytestmark = pytest.mark.anyio

from app.core.time import utc_today
from app.domains.bookings.models import BookingStatus
from app.domains.payments.service import WebhookAuthError, verify_signature
from tests import helpers

URL = "/api/v1/webhooks/payment"


async def _processing_booking() -> dict:
    """PROCESSING booking on room 201 backed by an active hold (pay scenario)."""
    check_in = utc_today() + timedelta(days=7)
    check_out = utc_today() + timedelta(days=9)
    await helpers.create_hold(201, helpers.GUEST_1)
    created = await helpers.create_booking(
        helpers.GUEST_1, 201, check_in, check_out, BookingStatus.PROCESSING, 130000.0
    )
    assert created["ref"], "bookings.ref should be generated by the DB"
    return created


async def _post(client, raw: bytes, sig: str | None):
    headers = {"Content-Type": "application/json"}
    if sig is not None:
        headers["X-Signature"] = sig
    return await client.post(URL, content=raw, headers=headers)


async def test_valid_event_confirms_booking(client):
    created = await _processing_booking()
    event = helpers.make_event(event_id="evt_valid_001", reference=created["ref"], amount=created["total"])
    raw = helpers.encode_event(event)
    resp = await _post(client, raw, helpers.sign_raw(raw))
    assert resp.status_code == 200, resp.text
    assert resp.json() == {"status": "confirmed"}
    assert await helpers.get_booking_status(created["booking_id"]) == "confirmed"
    assert await helpers.count("payments", f"WHERE booking_id = {created['booking_id']}") == 1
    assert await helpers.count("processed_events", "WHERE event_id = 'evt_valid_001'") == 1
    assert await helpers.count("room_nights", f"WHERE booking_id = {created['booking_id']}") == 2
    assert await helpers.count("holds", "WHERE room_id = 201") == 0


async def test_duplicate_retry_is_idempotent(client):
    created = await _processing_booking()
    event = helpers.make_event(event_id="evt_dup_001", reference=created["ref"], amount=created["total"])
    raw = helpers.encode_event(event)
    sig = helpers.sign_raw(raw)
    assert (await _post(client, raw, sig)).json() == {"status": "confirmed"}
    resp = await _post(client, raw, sig)
    assert resp.status_code == 200, resp.text
    assert resp.json() == {"status": "duplicate"}
    assert await helpers.count("payments", f"WHERE booking_id = {created['booking_id']}") == 1


async def test_wrong_signature_returns_401_and_writes_nothing(client):
    created = await _processing_booking()
    event = helpers.make_event(event_id="evt_bad_001", reference=created["ref"], amount=created["total"])
    raw = helpers.encode_event(event)
    resp = await _post(client, raw, "deadbeef" * 8)
    assert resp.status_code == 401, resp.text
    assert await helpers.count("processed_events", "WHERE event_id = 'evt_bad_001'") == 0
    assert await helpers.get_booking_status(created["booking_id"]) == "processing"


async def test_missing_signature_returns_401(client):
    created = await _processing_booking()
    event = helpers.make_event(event_id="evt_nosig_001", reference=created["ref"], amount=created["total"])
    raw = helpers.encode_event(event)
    assert (await _post(client, raw, None)).status_code == 401


async def test_tampered_body_fails_signature(client):
    created = await _processing_booking()
    event = helpers.make_event(event_id="evt_tamper_001", reference=created["ref"], amount=created["total"])
    raw = helpers.encode_event(event)
    sig = helpers.sign_raw(raw)
    tampered = helpers.encode_event({**event, "amount": created["total"] + 5000})
    resp = await _post(client, tampered, sig)
    assert resp.status_code == 401, resp.text


