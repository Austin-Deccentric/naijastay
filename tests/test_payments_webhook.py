async def test_invalid_json_with_valid_signature_returns_422(client):
    raw = b"{not-json"
    resp = await _post(client, raw, helpers.sign_raw(raw))
    assert resp.status_code == 422, resp.text


async def test_verify_signature_unit():
    secret = helpers.webhook_secret()
    raw = b'{"a":1}'
    verify_signature(raw, helpers.sign_raw(raw, secret))  # must not raise
    with pytest.raises(WebhookAuthError):
        verify_signature(raw, "wrong")
    with pytest.raises(WebhookAuthError):
        verify_signature(raw, "")
